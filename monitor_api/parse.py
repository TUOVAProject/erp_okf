"""
The Monitor pages are generated by docfx 2.59 and are far more structured than
plain text scraping suggests. Two facts drive this parser:

1. A relative href of the form ``Monitor.API.<Category>.<Class>.html`` is an
   exact pointer to another entity page. Absolute ``https://docs.microsoft.com``
   hrefs are .NET primitives. That single distinction replaces all pluralisation
   guessing and all "References ..." prose regexes.
2. Per-property facts live in ``<li>`` elements with a small closed vocabulary:
   ``Expandable``, ``Not nullable``, ``Unique``, ``Bitmask``, ``Obsolete``,
   ``Max length is N``, ``References<Target>`` and enum members ``Name: 0``.

Whatever this module cannot classify is preserved (``other_bullets``) rather
than dropped, so unknown markup shows up in the build report instead of
silently vanishing.
"""

import json
import re
from pathlib import Path

from bs4 import BeautifulSoup

from .paths import HTML_DIR

DOC_URL_TEMPLATE = "https://api.monitor.se/api/Monitor.API.{category}.{api_class}.html"

# Relative link to another entity page.
XREF_PATTERN = re.compile(r"^Monitor\.API\.([A-Za-z0-9_]+)\.([A-Za-z0-9_]+)\.html$")

# "BuyerPays: 1", "Goods trade: 1", "ManualDiscount: 99 (Introduced in version 25.6)"
ENUM_MEMBER_PATTERN = re.compile(
    r"^([A-Za-z_][A-Za-z0-9_ ]*?)\s*:\s*(-?\d+)"
    r"(?:\s*\(Introduced in version\s+([0-9][0-9.]*)\))?$"
)

# "Max length is 35" / "Min length is 1"
MAX_LENGTH_PATTERN = re.compile(r"^Max length is (\d+)$", re.IGNORECASE)
MIN_LENGTH_PATTERN = re.compile(r"^Min length is (\d+)$", re.IGNORECASE)

# "Obsolete since version 2.48 (Replaced by Part)"
OBSOLETE_PATTERN = re.compile(
    r"^Obsolete since version\s+([0-9][0-9.]*)\s*(?:\((.*)\))?$", re.IGNORECASE
)

# "Unique (per Part)" / "Mandatory (If customer invoices)"
QUALIFIED_FLAG_PATTERN = re.compile(r"^(Unique|Mandatory)\s*\((.*)\)$", re.IGNORECASE)

# "0 by default" / "From the activity type by default"
DEFAULT_PATTERN = re.compile(r"^(.*?)\s+by default$", re.IGNORECASE)

# Trailing "References PaymentTerms" in a summary; the link is captured
# separately, so the prose repetition is dropped. The target name is optional
# because an unrendered <see cref> leaves "References" with nothing after it, and
# the word repeats because a few source pages say "References References <link>".
TRAILING_REFERENCE_PATTERN = re.compile(r"\s*(?:References\s*)+([A-Za-z0-9_]+)?\s*$")

# Some summary cells contain a docfx cross-reference that the generator failed to
# render into an <a>, e.g.
#     References <see cref="P:Monitor.API.Sales.CustomerOrder.PaymentMethod"></see>
# The tag survives verbatim in the HTML. Left unhandled these are silently lost
# foreign keys; model.py resolves them in a second pass.
CREF_PATTERN = re.compile(r"^([A-Z]):Monitor\.API\.(.+)$")

# "Queryable, Introduced in version 2.18" / "Command, ..." / "Type, ..."
PAGE_KIND_PATTERN = re.compile(r"^\s*(Queryable|Command|Type)\b", re.IGNORECASE)
INTRODUCED_PATTERN = re.compile(r"Introduced in version\s+([0-9][0-9.]*)", re.IGNORECASE)

HTTP_VERB_PATTERN = re.compile(r"^(GET|POST|PUT|PATCH|DELETE)\s+(\S+)")

PAGE_KIND_TO_ENTITY_KIND = {
    "queryable": "entity",
    "command": "command",
    "type": "type",
}


def collapse_whitespace(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def entity_key_from_href(href: str):
    """Resolve a docfx xref href to an entity key, or None if it is not one."""
    match = XREF_PATTERN.match((href or "").strip())

    if not match:
        return None

    return f"{match.group(1)}.{match.group(2)}"


def entity_refs_in_cell(cell) -> list[dict]:
    """Every entity page linked from a table cell, in document order."""
    refs = []
    seen = set()

    for anchor in cell.find_all("a", href=True):
        key = entity_key_from_href(anchor["href"])

        if key is None or key in seen:
            continue

        seen.add(key)
        refs.append({"target": key, "label": collapse_whitespace(anchor.get_text())})

    return refs


def crefs_in_cell(cell) -> list[dict]:
    """Unrendered docfx cross-references in a table cell, in document order.

    Resolution needs other pages' properties, so this only records what the tag
    said. ``prefix`` is the docfx member kind: ``P`` property, ``M`` method,
    ``F`` field, ``T`` type.
    """
    crefs = []
    seen = set()

    for tag in cell.find_all("see"):
        match = CREF_PATTERN.match((tag.get("cref") or "").strip())

        if not match or match.group(2) in seen:
            continue

        seen.add(match.group(2))
        crefs.append({"prefix": match.group(1), "member": match.group(2)})

    return crefs


def classify_bullets(cell) -> dict:
    """Split a summary cell's <li> items into structured facts.

    Returns the facts plus the prose summary with the <ul> blocks removed, so
    the summary is clean sentences rather than run-on constraint text.
    """
    facts = {
        "expandable": False,
        "not_nullable": False,
        "unique": False,
        "unique_scope": None,
        "bitmask": False,
        "obsolete": False,
        "obsolete_since": None,
        "obsolete_note": None,
        "mandatory": False,
        "mandatory_when": None,
        "max_length": None,
        "min_length": None,
        "default": None,
        "enum_values": [],
        "other_bullets": [],
    }

    for item in cell.find_all("li"):
        text = collapse_whitespace(item.get_text())
        lowered = text.lower()

        enum_match = ENUM_MEMBER_PATTERN.match(text)
        obsolete_match = OBSOLETE_PATTERN.match(text)
        qualified_match = QUALIFIED_FLAG_PATTERN.match(text)
        max_length_match = MAX_LENGTH_PATTERN.match(text)
        min_length_match = MIN_LENGTH_PATTERN.match(text)
        default_match = DEFAULT_PATTERN.match(text)

        if enum_match:
            facts["enum_values"].append(
                {
                    "name": enum_match.group(1).strip(),
                    "value": int(enum_match.group(2)),
                    "introduced_in": enum_match.group(3) or "",
                }
            )
        elif obsolete_match:
            facts["obsolete"] = True
            facts["obsolete_since"] = obsolete_match.group(1)
            facts["obsolete_note"] = (obsolete_match.group(2) or "").strip() or None
        elif qualified_match:
            flag, qualifier = qualified_match.group(1).lower(), qualified_match.group(2).strip()

            if flag == "unique":
                facts["unique"] = True
                facts["unique_scope"] = qualifier
            else:
                facts["mandatory"] = True
                facts["mandatory_when"] = qualifier
        elif max_length_match:
            facts["max_length"] = int(max_length_match.group(1))
        elif min_length_match:
            facts["min_length"] = int(min_length_match.group(1))
        elif lowered == "expandable":
            facts["expandable"] = True
        elif lowered == "not nullable":
            facts["not_nullable"] = True
        elif lowered == "unique":
            facts["unique"] = True
        elif lowered == "bitmask":
            facts["bitmask"] = True
        elif lowered == "obsolete":
            facts["obsolete"] = True
        elif lowered == "mandatory":
            facts["mandatory"] = True
        elif default_match:
            facts["default"] = default_match.group(1).strip()
        elif lowered.startswith("references"):
            # The link itself is picked up by entity_refs_in_cell; the bullet
            # carries no extra information.
            pass
        else:
            facts["other_bullets"].append(text)

    # Strip the bullet lists so the remaining text is prose only. This mutates
    # the cell, so callers must read links/bullets first.
    for unordered_list in cell.find_all("ul"):
        unordered_list.extract()

    facts["summary"] = TRAILING_REFERENCE_PATTERN.sub(
        "", collapse_whitespace(cell.get_text(" "))
    ).strip()

    return facts


def parse_type(raw_type: str) -> dict:
    """Split "Int64?" / "WithdrawalInformationLocation[]" into components."""
    text = collapse_whitespace(raw_type)
    nullable = text.endswith("?")

    if nullable:
        text = text[:-1].strip()

    is_collection = text.endswith("[]")
    element_type = text[:-2].strip() if is_collection else None

    return {
        "type": collapse_whitespace(raw_type),
        "base_type": text,
        "element_type": element_type,
        "is_collection": is_collection,
        "nullable_from_type": nullable,
    }


def parse_property_row(row) -> dict | None:
    cells = row.find_all("td")

    if len(cells) < 3:
        return None

    name = collapse_whitespace(cells[0].get_text())

    if not name:
        return None

    type_cell, summary_cell = cells[1], cells[2]
    introduced_in = collapse_whitespace(cells[3].get_text()) if len(cells) > 3 else ""

    type_info = parse_type(type_cell.get_text())

    # Read links before classify_bullets() strips the <ul> elements.
    type_refs = entity_refs_in_cell(type_cell)
    summary_refs = entity_refs_in_cell(summary_cell)
    summary_crefs = crefs_in_cell(summary_cell)
    facts = classify_bullets(summary_cell)

    # A link in the Type cell is a navigation property (the property *is* the
    # related entity). A link in the Summary cell is a foreign key (the property
    # holds the related entity's id).
    references = []
    seen = set()

    for ref in type_refs:
        references.append({"target": ref["target"], "label": ref["label"], "kind": "navigation"})
        seen.add(ref["target"])

    for ref in summary_refs:
        if ref["target"] in seen:
            continue
        references.append({"target": ref["target"], "label": ref["label"], "kind": "foreign_key"})
        seen.add(ref["target"])

    introduced_match = INTRODUCED_PATTERN.search(introduced_in)

    return {
        "name": name,
        "type": type_info["type"],
        "base_type": type_info["base_type"],
        "element_type": type_info["element_type"],
        "is_collection": type_info["is_collection"],
        "nullable": type_info["nullable_from_type"] and not facts["not_nullable"],
        "expandable": facts["expandable"],
        "unique": facts["unique"],
        "unique_scope": facts["unique_scope"],
        "bitmask": facts["bitmask"],
        "obsolete": facts["obsolete"],
        "obsolete_since": facts["obsolete_since"],
        "obsolete_note": facts["obsolete_note"],
        "mandatory": facts["mandatory"],
        "mandatory_when": facts["mandatory_when"],
        "max_length": facts["max_length"],
        "min_length": facts["min_length"],
        "default": facts["default"],
        "summary": facts["summary"],
        "introduced_in": introduced_match.group(1) if introduced_match else "",
        "enum_values": facts["enum_values"],
        "references": references,
        "pending_crefs": summary_crefs,
        "other_bullets": facts["other_bullets"],
    }


def section_pre_text(article, heading_id: str) -> str:
    heading = article.find("h2", id=heading_id)

    if heading is None:
        return ""

    block = heading.find_next("pre")

    return block.get_text().strip() if block else ""


def parse_endpoint(article) -> dict | None:
    """The first <pre> is the endpoint only if it starts with an HTTP verb.

    "Type" pages have no endpoint line at all, and their first <pre> is the JSON
    example — which the previous parser stored in the endpoint field for 25
    entities.
    """
    block = article.find("pre")

    if block is None:
        return None

    match = HTTP_VERB_PATTERN.match(block.get_text().strip())

    if not match:
        return None

    return {"method": match.group(1), "url": match.group(2)}


def parse_example(article):
    heading = article.find("h2", id="example")

    if heading is None:
        return None, None

    block = heading.find_next("pre")

    if block is None:
        return None, None

    raw = block.get_text().strip()

    try:
        return json.loads(raw), raw
    except json.JSONDecodeError:
        return None, raw


def parse_properties(article) -> list[dict]:
    heading = article.find("h2", id="properties")

    if heading is None:
        return []

    table = heading.find_next("table")

    if table is None:
        return []

    body = table.find("tbody") or table
    properties = []

    for row in body.find_all("tr"):
        parsed = parse_property_row(row)

        if parsed is not None:
            properties.append(parsed)

    return properties


def parse_page(path: Path) -> dict:
    """Parse one html/<Category>/<ApiClass>.html page.

    Identity comes from the file path, not from the <h1>. Two Sales pages both
    render <h1>Create</h1>, and keying on the heading made one silently
    overwrite the other.
    """
    category = path.parent.name
    api_class = path.stem
    article = BeautifulSoup(path.read_text(encoding="utf-8"), "html.parser").find(
        "article", id="_content"
    )

    if article is None:
        raise ValueError(f"no <article id='_content'> in {path}")

    heading = article.find("h1")
    paragraphs = [collapse_whitespace(p.get_text(" ")) for p in article.find_all("p")]
    paragraphs = [p for p in paragraphs if p]

    info = paragraphs[0] if paragraphs else ""
    kind_match = PAGE_KIND_PATTERN.match(info)
    introduced_match = INTRODUCED_PATTERN.search(info)
    example, example_raw = parse_example(article)

    return {
        "key": f"{category}.{api_class}",
        "category": category,
        "api_class": api_class,
        "name": collapse_whitespace(heading.get_text()) if heading else api_class,
        "kind": PAGE_KIND_TO_ENTITY_KIND.get(
            kind_match.group(1).lower() if kind_match else "", "unknown"
        ),
        "introduced_in": introduced_match.group(1) if introduced_match else "",
        "info": info,
        "description": paragraphs[1] if len(paragraphs) > 1 else "",
        "notes": paragraphs[2:],
        "endpoint": parse_endpoint(article),
        "guid": section_pre_text(article, "guid"),
        "required_permission": section_pre_text(article, "required-permission"),
        "properties": parse_properties(article),
        "example": example,
        "example_raw": example_raw,
        "source_file": str(path.relative_to(HTML_DIR.parent).as_posix()),
        "source_url": DOC_URL_TEMPLATE.format(category=category, api_class=api_class),
    }


def parse_all() -> list[dict]:
    pages = []

    for path in sorted(HTML_DIR.glob("*/*.html")):
        pages.append(parse_page(path))

    return pages
